use std::{fs, path::Path};

fn ensure_fallback_icon() {
    let path = Path::new("icons/icon.png");
    if path.exists() {
        return;
    }

    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }

    // 1x1 RGBA PNG. This is only a development fallback so Tauri's
    // generate_context macro always receives a valid RGBA icon.
    const PNG: &[u8] = &[
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
        0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89,
        0x00, 0x00, 0x00, 0x0D, 0x49, 0x44, 0x41, 0x54,
        0x08, 0xD7, 0x63, 0x60, 0x60, 0x60, 0xF8, 0x0F, 0x00,
        0x01, 0x04, 0x01, 0x00, 0x5F, 0xE5, 0xC3, 0x4B,
        0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
        0xAE, 0x42, 0x60, 0x82,
    ];

    fs::write(path, PNG).expect("failed to write fallback RGBA app icon");
}

fn main() {
    ensure_fallback_icon();
    tauri_build::build()
}
